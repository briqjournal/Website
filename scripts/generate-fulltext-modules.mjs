import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";

const root = process.cwd();
const appDir = join(root, "app");
const outputRoot = join(appDir, "generated-fulltext");
const currentOutput = join(outputRoot, "current");
const archiveOutput = join(outputRoot, "en-archive");
const safeSlug = /^[a-z0-9-]+$/;

async function readJson(path) {
  return JSON.parse(await readFile(path, "utf8"));
}

function assertSlug(slug, source) {
  if (!safeSlug.test(slug)) {
    throw new Error(`Unsafe article slug in ${source}: ${slug}`);
  }
}

async function writeEntries(entries, directory, source) {
  await mkdir(directory, { recursive: true });
  for (const [slug, value] of entries) {
    assertSlug(slug, source);
    await writeFile(
      join(directory, `${slug}.json`),
      `${JSON.stringify(value)}\n`,
      "utf8",
    );
  }
}

const currentSource = join(appDir, "article-fulltext-current.json");
const archiveSource = join(appDir, "article-fulltext-en-archive.json");
const current = await readJson(currentSource);
const archive = await readJson(archiveSource);
const currentEntries = Object.entries(current).sort(([a], [b]) => a.localeCompare(b));
const archiveEntries = Object.entries(archive).sort(([a], [b]) => a.localeCompare(b));

await rm(outputRoot, { recursive: true, force: true });
await writeEntries(currentEntries, currentOutput, "article-fulltext-current.json");
await writeEntries(archiveEntries, archiveOutput, "article-fulltext-en-archive.json");

const loaderLines = (entries, directory) => entries
  .map(([slug]) => `  ${JSON.stringify(slug)}: () => import(${JSON.stringify(`./${directory}/${slug}.json`)}),`)
  .join("\n");

const loaderSource = `// Generated by scripts/generate-fulltext-modules.mjs. Do not edit by hand.\n` +
`type JsonModule = { default: unknown };\n\n` +
`const currentFullTextLoaders: Record<string, () => Promise<JsonModule>> = {\n${loaderLines(currentEntries, "current")}\n};\n\n` +
`const archiveEnglishFullTextLoaders: Record<string, () => Promise<JsonModule>> = {\n${loaderLines(archiveEntries, "en-archive")}\n};\n\n` +
`async function loadFrom(loaders: Record<string, () => Promise<JsonModule>>, slug: string) {\n` +
`  const loader = loaders[slug];\n` +
`  if (!loader) return undefined;\n` +
`  const module = await loader();\n` +
`  return module.default;\n` +
`}\n\n` +
`export function loadCurrentFullText(slug: string) {\n` +
`  return loadFrom(currentFullTextLoaders, slug);\n` +
`}\n\n` +
`export function loadArchiveEnglishFullText(slug: string) {\n` +
`  return loadFrom(archiveEnglishFullTextLoaders, slug);\n` +
`}\n\n` +
`export async function loadSaudiEnglishFullText() {\n` +
`  const module = await import("../article-fulltext-saudi-en.json");\n` +
`  return module.default;\n` +
`}\n`;

await writeFile(join(outputRoot, "loaders.ts"), loaderSource, "utf8");
console.log(`Generated ${currentEntries.length} current full-text modules and ${archiveEntries.length} English archive modules in ${relative(root, outputRoot)}.`);
