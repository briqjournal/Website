import { mkdir, rm, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import { loadFullTextCollections } from "./content-store.mjs";

const root = process.cwd();
const appDir = join(root, "app");
const outputRoot = join(appDir, "generated-fulltext");
const currentOutput = join(outputRoot, "current");
const archiveOutput = join(outputRoot, "en-archive");
const safeSlug = /^[a-z0-9-]+$/;

function assertSlug(slug, source) {
  if (!safeSlug.test(slug)) throw new Error(`Unsafe article slug in ${source}: ${slug}`);
}

async function writeEntries(entries, directory, source) {
  await mkdir(directory, { recursive: true });
  for (const [slug, value] of entries) {
    assertSlug(slug, source);
    await writeFile(join(directory, `${slug}.json`), `${JSON.stringify(value)}\n`, "utf8");
  }
}

const { current, enArchive, saudiEn } = await loadFullTextCollections(root);
const currentEntries = Object.entries(current);
const archiveEntries = Object.entries(enArchive);

await rm(outputRoot, { recursive: true, force: true });
await writeEntries(currentEntries, currentOutput, "content current full text");
await writeEntries(archiveEntries, archiveOutput, "content English archive full text");
await mkdir(outputRoot, { recursive: true });
await writeFile(join(outputRoot, "saudi-en.json"), `${JSON.stringify(saudiEn)}\n`, "utf8");

// Compatibility aggregates are generated for existing tests and legacy import tools.
// They are ignored by Git and are never canonical sources.
await writeFile(join(appDir, "article-fulltext-current.json"), `${JSON.stringify(current, null, 2)}\n`, "utf8");
await writeFile(join(appDir, "article-fulltext-en-archive.json"), `${JSON.stringify(enArchive, null, 2)}\n`, "utf8");
await writeFile(join(appDir, "article-fulltext-saudi-en.json"), `${JSON.stringify(saudiEn, null, 2)}\n`, "utf8");

const loaderLines = (entries, directory) => entries
  .map(([slug]) => `  ${JSON.stringify(slug)}: () => import(${JSON.stringify(`./${directory}/${slug}.json`)}),`)
  .join("\n");

const loaderSource = `// Generated by scripts/generate-fulltext-modules.mjs. Do not edit by hand.
type JsonModule = { default: unknown };

const currentFullTextLoaders: Record<string, () => Promise<JsonModule>> = {
${loaderLines(currentEntries, "current")}
};

const archiveEnglishFullTextLoaders: Record<string, () => Promise<JsonModule>> = {
${loaderLines(archiveEntries, "en-archive")}
};

async function loadFrom(loaders: Record<string, () => Promise<JsonModule>>, slug: string) {
  const loader = loaders[slug];
  if (!loader) return undefined;
  const module = await loader();
  return module.default;
}

export function loadCurrentFullText(slug: string) {
  return loadFrom(currentFullTextLoaders, slug);
}

export function loadArchiveEnglishFullText(slug: string) {
  return loadFrom(archiveEnglishFullTextLoaders, slug);
}

export async function loadSaudiEnglishFullText() {
  const module = await import("./saudi-en.json");
  return module.default;
}
`;

await writeFile(join(outputRoot, "loaders.ts"), loaderSource, "utf8");
console.log(`Generated ${currentEntries.length} current full-text modules and ${archiveEntries.length} English archive modules in ${relative(root, outputRoot)}.`);
